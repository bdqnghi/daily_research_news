#!/usr/bin/env python3
"""Render LinkedIn likes by exact post publication day, matching the X archive."""
import argparse
import json
import os
import re
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import parse_qs, urlsplit


def normalized_url(url):
    p = urlsplit(url)
    host = (p.hostname or '').lower().removeprefix('www.')
    path = p.path.rstrip('/')
    if host in {'arxiv.org', 'export.arxiv.org'}:
        match = re.search(r'/(?:abs|pdf|html)/([^?#]+)', path)
        if match:
            paper = re.sub(r'v\d+$', '', match[1].removesuffix('.pdf'))
            return f'arxiv.org/abs/{paper}'
    query = parse_qs(p.query)
    for key in list(query):
        if key.startswith('utm_') or key in {'fbclid', 'gclid', 'rcm', 'trk'}:
            del query[key]
    suffix = '&'.join(f'{k}={v}' for k in sorted(query) for v in query[k])
    return host + path + ('?' + suffix if suffix else '')


def markdown_text(value):
    return re.sub(r'\s+', ' ', value).strip().replace('[', '\\[').replace(']', '\\]')


def publication_timestamp(url):
    """Read the Unix-millisecond timestamp encoded in a LinkedIn post ID.

    All arithmetic stays integral to preserve the 19-digit identifier.
    Source/method: https://github.com/dan0dev/linkedin-timestamp
    """
    match = re.search(r'(?:activity|share|ugcPost)[-:](\d{16,20})', url)
    if not match:
        raise ValueError(f'No LinkedIn post identifier: {url}')
    milliseconds = int(match[1]) >> 22
    return datetime.fromtimestamp(milliseconds / 1000, timezone.utc)


def render_day(day, posts, destination, x_index):
    lines = [f'# LinkedIn Likes — {day}', '', '## Key Topics', '']
    lines += [f"- **{markdown_text(p['author'])}** — {p['summary']}" for p in posts]
    lines += ['', '---', '## Liked Posts', '']
    for p in posts:
        timestamp = datetime.fromisoformat(p['published_at'].replace('Z', '+00:00'))
        lines += [f"### {markdown_text(p['author'])}",
                  f"[Post]({p['post_url']}) · [Author]({p['author_url']})", '',
                  f"Published: {timestamp.strftime('%Y-%m-%d %H:%M UTC')}", '',
                  '> **Summary:** ' + p.get('details', p['summary']).replace('\n', '\n> '), '']
        for link in p['external_links']:
            lines.append(f"📎 [{markdown_text(link['title'])}]({link['url']})")
        matches = sorted({path for link in p['external_links']
                          for path in x_index.get(normalized_url(link['url']), set())})
        if matches:
            lines += ['', 'Also in X: ' + ', '.join(
                f'[{path.stem}]({os.path.relpath(path, destination.parent)})' for path in matches) + '.']
        counts = p.get('engagement')
        if counts:
            lines += ['', f"❤️ {counts['reactions']} | 💬 {counts['comments']} | 🔁 {counts['reposts']}"]
        lines += ['', '---', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[1])
    args = ap.parse_args()
    root = args.repo.resolve()
    source = root / 'LinkedIn'
    posts = json.loads((source / 'data/liked-posts.json').read_text())['posts']
    status_path = source / 'data/import-status.json'
    status = json.loads(status_path.read_text())
    assert len({p['id'] for p in posts}) == len(posts), 'Duplicate records'
    assert all(p['reaction'] == 'Like' for p in posts)
    x_index = defaultdict(set)
    for path in sorted((root / 'X').glob('20*/*/*.md')):
        for url in re.findall(r'https?://[^\s)>]+', path.read_text()):
            x_index[normalized_url(url)].add(path)
    days = defaultdict(list)
    pending = []
    for p in posts:
        if not p.get('published_at'):
            pending.append(p)
            continue
        decoded = publication_timestamp(p['post_url'])
        recorded = datetime.fromisoformat(p['published_at'].replace('Z', '+00:00'))
        assert decoded == recorded, f"Publication timestamp mismatch: {p['id']}"
        assert p['published_on'] == decoded.date().isoformat()
        days[p['published_on']].append(p)
    outputs = {}
    for day, day_posts in sorted(days.items()):
        day_posts.sort(key=lambda p: (p['published_at'], p['id']), reverse=True)
        path = source / day[:4] / day[5:7] / f'{day}.md'
        outputs[path] = render_day(day, day_posts, path, x_index)
    # Only remove files generated by the previous LinkedIn daily/part renderer.
    obsolete = set(source.glob('20*/*/*/part-*.md')) | set(source.glob('20*/*/20??-??-??.md'))
    for path in obsolete - outputs.keys():
        path.unlink()
    for folder in list(source.glob('20*/*/20??-??-??')):
        if folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content.rstrip() + '\n')
    pending_path = source / 'pending-publication-dates.md'
    if pending:
        lines = ['# Posts awaiting exact publication dates', '',
                 'These entries are preserved here until their original post permalinks are recovered. They are deliberately excluded from dated notes; collection dates and relative ages are not substituted for publication dates.', '']
        for p in pending:
            lines += [f"### {markdown_text(p['author'])}",
                      f"[Author]({p['author_url']})", '',
                      '> **Summary:** ' + p.get('details', p['summary']), '']
            for link in p['external_links']:
                lines.append(f"📎 [{markdown_text(link['title'])}]({link['url']})")
            lines += ['', '---', '']
        pending_path.write_text('\n'.join(lines))
    elif pending_path.exists():
        pending_path.unlink()
    dated_count = sum(len(v) for v in days.values())
    status.update({'date_basis': 'post_publication_utc', 'publication_dates_resolved': dated_count,
                   'publication_dates_pending': len(pending), 'daily_note_count': len(days),
                   'post_summaries': len(posts),
                   'post_urls_captured': sum(bool(p.get('post_url')) for p in posts),
                   'detailed_summaries': sum(bool(p.get('details')) for p in posts)})
    status_path.write_text(json.dumps(status, ensure_ascii=False, indent=2) + '\n')
    readme = ['# LinkedIn Research News', '',
              'Daily research notes grouped by the exact publication day of each liked post, matching `X/YYYY/MM/YYYY-MM-DD.md`.', '',
              '## Daily notes', '']
    for day, day_posts in sorted(days.items(), reverse=True):
        readme.append(f'- [{day}]({day[:4]}/{day[5:7]}/{day}.md) — {len(day_posts)} posts')
    if pending:
        readme += ['', f'[{len(pending)} posts awaiting exact publication dates](pending-publication-dates.md).']
    readme += ['', '## Format', '',
               'Each daily file contains Key Topics and Liked Posts. Entries include the author, original post permalink, a substantive summary, research links, and engagement counts when captured. Summaries describe author-reported findings rather than independently verified results.', '',
               'Dates use UTC, matching the existing X pipeline. The precise timestamp is decoded from the original LinkedIn post identifier; relative ages and collection dates are never used to assign a day. [Timestamp decoding method](https://github.com/dan0dev/linkedin-timestamp).', '',
               '## Coverage', '',
               f"- {len(posts)} post summaries from {status['post_like_observations']} observed post-like items.",
               f'- {dated_count} posts placed into {len(days)} exact daily notes; {len(pending)} remain undated.',
               '- Earlier 2026 history remains incomplete. The requested LinkedIn account export is still pending and will help reconcile the complete inventory; it is not required to date a post with an original permalink.',
               '- Repeated wording is retained as separate posts when original permalinks differ. Two such pairs were verified. One comment-like was excluded.', '',
               '## Regenerate', '', '```bash', 'python3 scripts/generate_linkedin_notes.py', '```', '',
               'Normalized records: `data/liked-posts.json`. Import coverage: `data/import-status.json`.']
    (source / 'README.md').write_text('\n'.join(readme) + '\n')
    print(f'{dated_count} posts in {len(days)} exact daily notes; {len(pending)} undated; no numbered parts.')


if __name__ == '__main__':
    main()
